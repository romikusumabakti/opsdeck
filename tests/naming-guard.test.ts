import { describe, expect, it } from "vitest";

// The product is called Menara in code, tests and docs. This guard fails on
// any tracked file that still calls it "Panel" or mentions "Acme". UI copy
// takes the instance name at runtime ({{APP_NAME}}), so it never hard-codes
// the product either.

type Allowed = { path: RegExp; line: RegExp; reason: string };

const ALLOWED: Allowed[] = [
  {
    path: /./,
    line: /\.Panel\b/,
    reason: "Base UI parts: Tabs.Panel, Collapsible.Panel, *Primitive.Panel",
  },
  {
    path: /^lib\/ci\/pipeline\.ts$/,
    line: /Generated by .*Panel/,
    reason: "legacy pipeline marker regex and its comment",
  },
  {
    path: /^lib\/jira\/attribution\.ts$/,
    line: /<Name> Panel|\[A-Z\]\[A-Za-z\]\* Panel/,
    reason: "legacy attribution regex and its comment",
  },
  {
    path: /^tests\/(apps-registration-service|jira-attribution|setup-detect|new-environment-resolve)\.test\.ts$/,
    line: /Generated by (<Name>|Example|Acme) Panel|via (<Name>|Example) Panel/,
    reason: "fixtures written by older releases (legacy marker)",
  },
  {
    path: /^tests\/(i18n-branding|messages-naming)\.test\.ts$/,
    line: /Panel/,
    reason: "sample two-word instance name and the message naming checks",
  },
  {
    path: /^messages\/es\.json$/,
    line: /"Panel"/,
    reason: "Spanish word for a dashboard",
  },
  {
    path: /^tests\/naming-guard\.test\.ts$/,
    line: /./,
    reason: "this file names the words it forbids",
  },
];

function grepTracked(): { path: string; lineNo: string; text: string }[] {
  const result = Bun.spawnSync(
    [
      "git",
      "grep",
      "-n",
      "-I",
      "-P",
      "\\bPanel\\b|\\bDSS\\b",
      "--",
      ".",
      ":!www",
      ":!bun.lock",
    ],
    { cwd: new URL("..", import.meta.url).pathname }
  );
  // Exit 1 means no match; anything above is a real failure.
  if (result.exitCode > 1) throw new Error(result.stderr.toString());
  return result.stdout
    .toString()
    .split("\n")
    .filter(Boolean)
    .map((raw) => {
      const [path = "", lineNo = "", ...rest] = raw.split(":");
      return { path, lineNo, text: rest.join(":") };
    });
}

const isAllowed = (hit: { path: string; text: string }, a: Allowed) =>
  a.path.test(hit.path) && a.line.test(hit.text);

describe("naming guard", () => {
  const hits = grepTracked();

  it("no tracked file calls the product Panel or names Acme", () => {
    const remaining = hits
      .filter((hit) => !ALLOWED.some((a) => isAllowed(hit, a)))
      .map((hit) => `${hit.path}:${hit.lineNo}`);
    expect(remaining).toEqual([]);
  });

  it("the allowlist has no stale entries", () => {
    const stale = ALLOWED.filter(
      (a) => !hits.some((hit) => isAllowed(hit, a))
    ).map((a) => a.reason);
    expect(stale).toEqual([]);
  });
});
