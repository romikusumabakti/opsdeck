import { describe, expect, it } from "vitest";

// The product is called Menara in code, tests and docs. This guard fails on
// any tracked file that still calls it "panel" (any case) or mentions "Acme".
// UI copy takes the instance name at runtime ({{APP_NAME}}), so it never
// hard-codes the product either.
//
// Each allowlist entry names the construct it exempts. The matches are
// removed from the line first; anything left that still says panel/Acme fails,
// so prose beside an allowed construct is still caught. The component-file
// entry is the one wide exemption: "panel" there is a UI panel, not the product.

type Allowed = {
  path: RegExp;
  construct: RegExp;
  reason: string;
};

const ANY = /./;
const ALLOWED: Allowed[] = [
  {
    path: ANY,
    construct: /\b\w+\.Panel\b/g,
    reason: "Base UI parts: Tabs.Panel, Collapsible.Panel, *Primitive.Panel",
  },
  {
    path: ANY,
    construct:
      /\b(?:live-run|draft|provisioning|clock-state)-panel\b|data-\[panel-open\]/g,
    reason: "UI component file names and the Base UI panel-open data attribute",
  },
  {
    path: /^lib\/ci\/(pipeline|build-spec)\.ts$/,
    construct:
      /Generated by <Name> Panel|\[A-Z\]\[A-Za-z\]\* Panel|"notify-panel"/g,
    reason: "legacy pipeline marker regex, its comment, and the old step name",
  },
  {
    path: /^lib\/jira\/attribution\.ts$/,
    construct: /via <Name> Panel|\[A-Z\]\[A-Za-z\]\* Panel/g,
    reason: "legacy attribution regex and its comment",
  },
  {
    path: /^lib\/jira\/adf\.ts$|^tests\/jira-adf\.test\.ts$/,
    construct: /type: "panel"|\bpanel border\b/g,
    reason: "Jira ADF panel node",
  },
  {
    path: /^tests\/(apps-registration-service|jira-attribution|setup-detect|new-environment-resolve|ci-pipeline)\.test\.ts$/,
    construct:
      /Generated by (?:<Name>|Example|Acme) Panel|via (?:<Name>|Example) Panel|\bnotify-panel\b|in the Panel, not this file/g,
    reason: "fixtures written by older releases (legacy marker, old step name)",
  },
  {
    path: /^tests\/(i18n-branding|messages-naming)\.test\.ts$/,
    construct:
      /\["Acme", "Panel"\]|# in Acme Panel|"Panel" or a localized|no message names the product Panel|"panel" is also the ordinary word|panelWritten|panelRead|no old panel key|\.panel\b|\\bpanel\\b|\\bpanel\\s\+|\bnotify-panel\b/g,
    reason: "sample two-word instance name and the message naming checks",
  },
  {
    path: /^messages\/es\.json$/,
    construct: /\bpanel\b/gi,
    reason: "Spanish word for a dashboard",
  },
  {
    path: /^design\/motifs\/prompts\.json$/,
    construct: /\bpanels?\b/gi,
    reason: "illustration prompt: framed panels of a carved ornament",
  },
  {
    path: /^README\.md$/,
    construct: /operations panel|another panel|PaaS panels|similar panels/g,
    reason: "generic category word for this kind of tool",
  },
  {
    path: /^(components\/(file-explorer|live-run-panel|live-run-dialog|code-editor|server-form|ui\/context-menu)\.tsx|web\/components\/assistant\/(assistant-workspace|draft-panel|mention-popover)\.tsx|web\/routes\/\$locale\/_app\/(\$projectKey\.index\.tsx|-components\/(env\/(provisioning-panel|skeletons|settings\/variables-tab|mock-time\/mock-time-(api|legacy))|issues-client|setup\/new-environment-form)\.tsx)|server\/services\/provisioning\.ts|tests\/(assistant-ui\.test\.tsx|provisioning-api\.test\.ts|provisioning-panel\.test\.tsx))$/,
    construct: /\bpanel\b/g,
    reason:
      "a UI panel (drafts, provisioning, file explorer, ...), not the product",
  },
  {
    path: /^lib\/(knowledge|db\/schema)\.ts$/,
    construct: /"Referenced by" panel/g,
    reason: "the knowledge page's Referenced by panel",
  },
  {
    path: /^tests\/naming-guard\.test\.ts$/,
    construct: /\bpanel\b|\bDSS\b/gi,
    reason: "this file names the words it forbids",
  },
];

function grepTracked(): { path: string; lineNo: string; text: string }[] {
  const result = Bun.spawnSync(
    [
      "git",
      "grep",
      "-n",
      "-I",
      "-P",
      "(?i:\\bpanel\\b)|\\bDSS\\b",
      "--",
      ".",
      ":!www",
      ":!bun.lock",
    ],
    { cwd: new URL("..", import.meta.url).pathname }
  );
  // Exit 1 means no match; anything above is a real failure.
  if (result.exitCode > 1) throw new Error(result.stderr.toString());
  return result.stdout
    .toString()
    .split("\n")
    .filter(Boolean)
    .map((raw) => {
      const [path = "", lineNo = "", ...rest] = raw.split(":");
      return { path, lineNo, text: rest.join(":") };
    });
}

const FORBIDDEN = /\bpanel\b|\bDSS\b/i;
const applicable = (path: string) => ALLOWED.filter((a) => a.path.test(path));

describe("naming guard", () => {
  const hits = grepTracked();

  it("no tracked file calls the product panel or names Acme", () => {
    const remaining = hits
      .filter((hit) => {
        let text = hit.text;
        for (const a of applicable(hit.path)) {
          text = text.replace(a.construct, "");
        }
        return FORBIDDEN.test(text);
      })
      .map((hit) => `${hit.path}:${hit.lineNo}`);
    expect(remaining).toEqual([]);
  });

  it("the allowlist has no stale entries", () => {
    const stale = ALLOWED.filter(
      (a) =>
        !hits.some(
          (hit) =>
            a.path.test(hit.path) && new RegExp(a.construct).test(hit.text)
        )
    ).map((a) => a.reason);
    expect(stale).toEqual([]);
  });
});
