/**
 * App registration: activates each component's repository in Woodpecker,
 * clears any configuration extension on it, gives it a notify secret, and only
 * then stores the app. A generated component's pipeline lives only in the
 * repo: the generated `.woodpecker.yaml` is committed afterwards to every
 * branch the component builds; a failed branch is recorded, never undone into
 * the rest.
 *
 * Engineers register custom components; generated components, pipeline file
 * commits and notify secret rotation need org integration:manage (admins).
 */

const NOTIFY_SECRET_NAME = "opsdeck_notify";
const NOTIFY_SECRET_EVENTS: ("push" | "manual")[] = ["push", "manual"];
const CUSTOM_TIMEOUT_MINUTES = 60;
const PIPELINE_FILE_PATH = ".woodpecker.yaml";
const PIPELINE_FILE_MESSAGE =
  "ci: update .woodpecker.yaml generated by DSS Panel\n\nEdit the component's build spec in the Panel instead of this file; the Panel overwrites it.";
/** How long after registration a registrant may start the first build. */
const FIRST_BUILD_WINDOW_MS = 60 * 60 * 1000;
const INTEGRATION_MANAGE = { integration: ["manage"] } as const;

type AppWithComponents = NonNullable<Awaited<ReturnType<typeof getApp>>>;

const fail = (status: 403 | 404 | 409 | 500 | 502, message: string): never => {
  throw new HTTPException(status, { message });
};

/**
 * Engineers of any project and admins (see canRegisterApp). Returns whether
 * the caller also has org integration:manage, which generated pipelines need.
 */
export async function requireRegistrant(): Promise<{
  canManagePipelines: boolean;
}> {
  const session = await requireSession();
  const access = await getProjectAccess();
  if (!canRegisterApp(session.user.role, Object.values(access.roles))) {
    forbidden();
  }
  return {
    canManagePipelines: canOrg(session.user.role, { ...INTEGRATION_MANAGE }),
  };
}

function newNotifySecret(): string {
  return randomBytes(32).toString("hex");
}

/** Runs one Woodpecker call, turning its failure into a 502 naming the step. */
async function step<T>(label: string, run: () => Promise<T>): Promise<T> {
  try {
    return await run();
  } catch (error) {
    if (error instanceof CiProviderError) {
      return fail(502, `${label} failed: ${error.message}`);
    }
    throw error;
  }
}

/** Any signed-in user: apps and components, never their notify secrets. */
export async function listAllApps(): Promise<AppWithComponents[]> {
  await requireSession();
  return listApps();
}

/** The CI connections a registrant may pick, without URLs or credentials. */
export async function listRegistrationConnections() {
  await requireRegistrant();
  return listConnectionOptions();
}

export type RegistrableRepo = CiRepo & { linkedComponentKey: string | null };

/** The connection's repos, each marked with the component it already builds. */
export async function listRegistrableRepos(
  connectionId: string
): Promise<RegistrableRepo[]> {
  await requireRegistrant();
  const provider = await getProviderForConnection(connectionId);
  const [repos, linked] = await Promise.all([
    step("Listing Woodpecker repositories", () => provider.listRepos()),
    linkedCiRepos(connectionId),
  ]);
  return repos.map((repo) => ({
    ...repo,
    linkedComponentKey:
      linked.find(
        (l) =>
          (repo.ciRepoId !== "" && l.ciRepoId === repo.ciRepoId) ||
          l.repoFullName === repo.fullName
      )?.componentKey ?? null,
  }));
}

/** The YAML a generated component would get, for the form's preview. */
export async function previewPipeline(
  componentKey: string,
  buildSpec: BuildSpec
): Promise<{ yaml: string }> {
  await requireRegistrant();
  return { yaml: generateWoodpeckerPipeline(componentKey, buildSpec) };
}

/** The branches a build spec builds, each once, in order. */
function builtBranches(spec: BuildSpec): string[] {
  return [...new Set(spec.branches)];
}

type CommitResult = { sha: string } | { error: string };

/**
 * Commits the generated pipeline file to each branch and records every
 * branch's outcome on the component. Never throws (Review Focus 4): a failed
 * branch is recorded and the next one is still tried.
 */
async function commitPipelineFiles(
  component: {
    componentKey: string;
    ciConnectionId: string;
    repoFullName: string;
  },
  branches: string[],
  yaml: string
): Promise<void> {
  let commit: (branch: string) => Promise<CommitResult>;
  try {
    const { forge, auth } = await getForgeCredentials(component.ciConnectionId);
    if (forge !== "bitbucket") {
      const error = `Committing to ${forge} is not supported`;
      commit = async () => ({ error });
    } else if (!auth) {
      const error = "The CI connection has no forge username and forge token";
      commit = async () => ({ error });
    } else {
      // Committing to a missing branch would make Bitbucket create it.
      commit = async (branch) => {
        if (!(await branchExists(auth, component.repoFullName, branch))) {
          return { error: `Branch ${branch} does not exist` };
        }
        return commitFile(
          auth,
          component.repoFullName,
          branch,
          PIPELINE_FILE_PATH,
          yaml,
          PIPELINE_FILE_MESSAGE
        );
      };
    }
  } catch (error) {
    console.error("Reading the forge credentials failed", error);
    commit = async () => ({ error: "The forge credentials could not be read" });
  }
  for (const branch of branches) {
    let result: CommitResult;
    try {
      result = await commit(branch);
    } catch (error) {
      // CiProviderError and the forge client's input checks carry messages
      // without credentials; anything else is reported generically.
      if (error instanceof CiProviderError) {
        result = { error: error.message };
      } else {
        console.error("Pipeline file commit failed", error);
        result = { error: "The commit failed unexpectedly" };
      }
    }
    try {
      await setPipelineFileCommit(component.componentKey, branch, result);
    } catch (error) {
      // The registration itself succeeded; a lost status is retried from the
      // app page.
      console.error("Recording the pipeline file commit failed", error);
    }
  }
}

type Prepared = {
  input: RegisterAppInput["components"][number];
  provider: CiProvider;
  yaml: string | null;
  repo?: CiRepo;
  secret?: string;
};

export async function registerApp(
  input: RegisterAppInput
): Promise<AppWithComponents> {
  const { canManagePipelines } = await requireRegistrant();
  if (
    !canManagePipelines &&
    input.components.some((c) => c.pipelineMode === "generated")
  ) {
    fail(403, "Only admins can register a component with a generated pipeline");
  }

  // Validate everything the Panel can know before touching Woodpecker.
  if (await appKeyExists(input.appKey)) {
    fail(409, `App ${input.appKey} already exists`);
  }
  const [taken] = await takenComponentKeys(
    input.components.map((c) => c.componentKey)
  );
  if (taken) fail(409, `Component ${taken} already exists`);

  const providers = new Map<string, CiProvider>();
  const prepared: Prepared[] = [];
  for (const component of input.components) {
    let provider = providers.get(component.ciConnectionId);
    if (!provider) {
      provider = await getProviderForConnection(component.ciConnectionId);
      providers.set(component.ciConnectionId, provider);
    }
    prepared.push({
      input: component,
      provider,
      yaml: component.buildSpec
        ? generateWoodpeckerPipeline(
            component.componentKey,
            component.buildSpec
          )
        : null,
    });
  }

  // Activate every repo first (Woodpecker reuses an already active one) and
  // refuse a repo that already builds a component, before any setting or
  // secret on it changes: overwriting its secret would break that component.
  for (const item of prepared) {
    const { componentKey, ciConnectionId, forgeRemoteId } = item.input;
    const repo = await step(
      `Activating the repository of ${componentKey} in Woodpecker`,
      () => item.provider.activateRepo(forgeRemoteId)
    );
    const linked = (await linkedCiRepos(ciConnectionId)).find(
      (l) =>
        (repo.ciRepoId !== "" && l.ciRepoId === repo.ciRepoId) ||
        l.repoFullName === repo.fullName
    );
    if (linked) {
      fail(
        409,
        `Repository ${repo.fullName} is already linked to component ${linked.componentKey}`
      );
    }
    if (!repo.ciRepoId) {
      fail(502, `Woodpecker returned no id for ${repo.fullName}`);
    }
    item.repo = repo;
  }

  for (const item of prepared) {
    const { componentKey, buildSpec } = item.input;
    const repo = item.repo as CiRepo;
    await step(`Updating the Woodpecker settings of ${repo.fullName}`, () =>
      item.provider.updateRepoSettings(repo.ciRepoId, {
        timeoutMinutes: buildSpec?.timeoutMinutes ?? CUSTOM_TIMEOUT_MINUTES,
        cancelPreviousOnPush: true,
        // The pipeline comes from the committed file only; clear any
        // extension so Woodpecker never depends on the Panel to build.
        configExtensionEndpoint: null,
      })
    );
    const secret = newNotifySecret();
    await step(
      `Storing the notify secret of ${componentKey} in Woodpecker`,
      () =>
        item.provider.upsertRepoSecret(
          repo.ciRepoId,
          NOTIFY_SECRET_NAME,
          secret,
          NOTIFY_SECRET_EVENTS
        )
    );
    item.secret = secret;
  }

  const rows: NewAppComponent[] = prepared.map((item) => ({
    componentKey: item.input.componentKey,
    ciConnectionId: item.input.ciConnectionId,
    repoFullName: (item.repo as CiRepo).fullName,
    ciRepoId: (item.repo as CiRepo).ciRepoId,
    bundleImage: item.input.bundleImage,
    notifySecret: encryptSecret(item.secret as string),
    pipelineMode: item.input.pipelineMode,
    buildSpec: item.input.buildSpec ?? null,
  }));
  try {
    await insertAppWithComponents(
      { appKey: input.appKey, name: input.name },
      rows
    );
  } catch (error) {
    if (isUniqueViolation(error)) {
      // Another registration won the race after this one had already
      // replaced the Woodpecker secret of the repo(s) it shares with it.
      const keys = prepared.map((item) => item.input.componentKey).join(", ");
      fail(
        409,
        `The app, a component or a repository was registered meanwhile. Woodpecker may now hold a notify secret the Panel does not know: rotate the notify secret of ${keys} on its app page.`
      );
    }
    throw error;
  }

  for (const item of prepared) {
    if (!item.yaml || !item.input.buildSpec) continue;
    await commitPipelineFiles(
      {
        componentKey: item.input.componentKey,
        ciConnectionId: item.input.ciConnectionId,
        repoFullName: (item.repo as CiRepo).fullName,
      },
      builtBranches(item.input.buildSpec),
      item.yaml
    );
  }

  return (await getApp(input.appKey)) ?? notFound();
}

async function requireAppComponent(appKey: string, componentKey: string) {
  const component = await getComponent(componentKey);
  if (!component || component.app.appKey !== appKey) notFound();
  return component as NonNullable<typeof component>;
}

/**
 * New notify secret: Woodpecker first, then the Panel, so a failure leaves
 * at most a Woodpecker secret the Panel does not know, and says so
 * (Review Focus 5).
 */
export async function rotateNotifySecret(
  appKey: string,
  componentKey: string
): Promise<{ ok: true }> {
  await requireOrgPermission({ ...INTEGRATION_MANAGE });
  const component = await requireAppComponent(appKey, componentKey);
  if (!component.ciRepoId) {
    fail(409, "This component has no Woodpecker repository");
  }
  const provider = await getProviderForConnection(component.ciConnectionId);
  const secret = newNotifySecret();
  try {
    await provider.upsertRepoSecret(
      component.ciRepoId as string,
      NOTIFY_SECRET_NAME,
      secret,
      NOTIFY_SECRET_EVENTS
    );
  } catch (error) {
    if (!(error instanceof CiProviderError)) throw error;
    fail(502, "Woodpecker secret not updated; Panel secret unchanged");
  }
  try {
    await setNotifySecret(componentKey, encryptSecret(secret));
  } catch (error) {
    console.error("Storing the rotated notify secret failed", error);
    fail(
      500,
      "Woodpecker has the new secret but the Panel does not — rotate again"
    );
  }
  return { ok: true };
}

/**
 * Commits the generated pipeline file again, to every built branch or to the
 * one given, and records the outcome per branch.
 */
export async function retryPipelineFileCommit(
  appKey: string,
  componentKey: string,
  branch?: string
): Promise<PublicAppComponent> {
  await requireOrgPermission({ ...INTEGRATION_MANAGE });
  const component = await requireAppComponent(appKey, componentKey);
  if (component.pipelineMode !== "generated" || !component.buildSpec) {
    fail(409, "This component does not use a generated pipeline");
  }
  const spec = component.buildSpec as BuildSpec;
  const branches = builtBranches(spec);
  if (branch !== undefined && !branches.includes(branch)) {
    badRequest(`The build spec does not build branch ${branch}`);
  }
  await commitPipelineFiles(
    component,
    branch === undefined ? branches : [branch],
    generateWoodpeckerPipeline(component.componentKey, spec)
  );
  const updated = (await getApp(appKey))?.components.find(
    (c) => c.componentKey === componentKey
  );
  return updated ?? notFound();
}

/**
 * Starts a build of the component's branch in Woodpecker (the New app
 * stepper's first build). Admins always may, any branch. Others may build
 * only the source branch of a deploy target of this component in a project
 * where they run deploys; an app with no environment yet
 * (the stepper has just registered it) is open to whoever may register apps,
 * for one hour after the app was created; later it is admins only.
 */
export async function triggerComponentBuild(
  appKey: string,
  componentKey: string,
  branch: string
): Promise<{ number: number }> {
  const session = await requireSession();
  const component = await requireAppComponent(appKey, componentKey);
  if (!canOrg(session.user.role, { ...INTEGRATION_MANAGE })) {
    const projectIds = await projectIdsWithAppEnvironment(component.appId);
    if (projectIds.length === 0) {
      // Only the first build of a fresh app: later, admins only.
      await requireRegistrant();
      if (
        Date.now() - component.app.createdAt.getTime() >
        FIRST_BUILD_WINDOW_MS
      ) {
        forbidden();
      }
    } else {
      // Only a branch a deploy target of this component deploys from, in a
      // project where the caller runs deploys.
      const [access, targets] = await Promise.all([
        getProjectAccess(),
        componentTargetBranches(component.componentKey),
      ]);
      if (
        !targets.some(
          (t) =>
            t.sourceBranch === branch &&
            canProject(access.roles[t.projectId] ?? null, { deploy: ["run"] })
        )
      ) {
        forbidden();
      }
    }
  }
  if (!component.ciRepoId) {
    throw new CodedHTTPException(
      409,
      "componentNotActivated",
      "This component has no Woodpecker repository"
    );
  }
  const provider = await getProviderForConnection(component.ciConnectionId);
  const pipeline = await step("Starting the build in Woodpecker", () =>
    provider.triggerPipeline(component.ciRepoId as string, branch)
  );
  await recordActivity({
    actorId: session.user.id,
    action: "app.build.trigger",
    entityType: "app",
    entityId: component.appId,
    data: {
      app: component.app.appKey,
      component: componentKey,
      branch,
      number: pipeline.number,
    },
  });
  return pipeline;
}
