const RESERVED: Record<DatabaseType, Set<string>> = {
  mssql: TSQL,
  postgres: POSTGRES,
  mysql: MYSQL,
};

export function isReservedWord(engine: DatabaseType, word: string): boolean {
  return RESERVED[engine].has(word.toLowerCase());
}
